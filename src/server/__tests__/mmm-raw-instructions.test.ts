// ── decodePool: byte-exact against the real historical pool account ─────

check('decodePool: decodes the real 849-byte pool account without error', () => {
  const buf = Buffer.from(REAL_POOL_ACCOUNT_HEX, 'hex');
  assert.strictEqual(buf.length, POOL_ACCOUNT_SIZE);
  const decoded = decodePool(buf);
  assert.ok(decoded);
});

check('decodePool: owner/cosigner/uuid/referral/allowlist match the real create_pool args exactly', () => {
  const decoded = decodePool(Buffer.from(REAL_POOL_ACCOUNT_HEX, 'hex'))!;
  assert.strictEqual(decoded.owner, REAL_OWNER);
  assert.strictEqual(decoded.cosigner, REAL_COSIGNER);
  assert.strictEqual(decoded.uuid, REAL_UUID);
  assert.strictEqual(decoded.referral, REAL_REFERRAL);
  assert.strictEqual(decoded.curveType, CURVE_KIND_EXP);
  assert.strictEqual(decoded.curveDelta, 300n);
  assert.strictEqual(decoded.lpFeeBp, 0);
  assert.strictEqual(decoded.buysideCreatorRoyaltyBp, 10_000);
  assert.strictEqual(decoded.allowlists[0].kind, ALLOWLIST_KIND.FVCA);
  assert.strictEqual(decoded.allowlists[0].value.toBase58(), REAL_ALLOWLIST_VALUE);
  for (let i = 1; i < ALLOWLIST_MAX_LEN; i++) assert.strictEqual(decoded.allowlists[i].kind, ALLOWLIST_KIND.EMPTY);
});

check('decodePool: rejects a buffer of the wrong length', () => {
  assert.strictEqual(decodePool(Buffer.alloc(848)), null);
  assert.strictEqual(decodePool(Buffer.alloc(850)), null);
});

// ── Quantity model: delta=0 constant price, and quantity → liquidity ────

check('quantity model: price 0.0118 SOL x quantity 1 == 11_800_000 lamports', () => {
  const pricePerNft = 11_800_000n;
  assert.strictEqual(pricePerNft * 1n, 11_800_000n);
});
for (const qty of [2, 5, 10]) {
  check(`quantity model: price 0.0118 SOL x quantity ${qty}`, () => {
    const pricePerNft = 11_800_000n;
    assert.strictEqual(pricePerNft * BigInt(qty), 11_800_000n * BigInt(qty));
  });
}
check('curveDelta=0 (linear) implies a constant per-fill price regardless of k — matches listings-store.ts formula', () => {
  const spot = 11_800_000n;
  const delta = 0n;
  for (const k of [0n, 1n, 2n, 9n]) {
    const priceAtK = spot + delta * k; // linear formula, delta=0 collapses to spot
    assert.strictEqual(priceAtK, spot);
  }
});

// ── normalizeAllowlists ──────────────────────────────────────────────────

check('normalizeAllowlists pads to exactly ALLOWLIST_MAX_LEN entries', () => {
  const out = normalizeAllowlists([{ kind: ALLOWLIST_KIND.MCC, value: pubkey(REAL_ALLOWLIST_VALUE) }]);
  assert.strictEqual(out.length, ALLOWLIST_MAX_LEN);
  assert.strictEqual(out[0].kind, ALLOWLIST_KIND.MCC);
  for (let i = 1; i < ALLOWLIST_MAX_LEN; i++) assert.strictEqual(out[i].kind, ALLOWLIST_KIND.EMPTY);
});

check('normalizeAllowlists throws when given more than ALLOWLIST_MAX_LEN entries', () => {
  const many = Array.from({ length: ALLOWLIST_MAX_LEN + 1 }, () => ({ kind: ALLOWLIST_KIND.ANY, value: PublicKey.default }));
  assert.throws(() => normalizeAllowlists(many));
});

